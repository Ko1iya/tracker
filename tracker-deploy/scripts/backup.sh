#!/usr/bin/env bash
#
# Бэкап прод-базы Tracker: логический дамп PostgreSQL + ретеншн старых копий.
# Копия шифруется gpg и уезжает в Timeweb S3 (бэкап на том же диске, что и база,
# спасает от кривой миграции, но не от смерти сервера).
# Раз в неделю дополнительно архивирует секреты и TLS-сертификаты.
#
# Запускается по расписанию из crontab (см. tracker-deploy/README.md).
# Ручной прогон:  /root/tracker/tracker-deploy/scripts/backup.sh

# set -e   — падать на первой же ошибке, а не бодро идти дальше с битым файлом;
# set -u   — обращение к необъявленной переменной это ошибка, а не пустая строка;
# pipefail — падать, если упало любое звено пайпа, а не только последнее.
set -euo pipefail

# --- Пути -------------------------------------------------------------------
# cron стартует с урезанным окружением и из домашнего каталога, поэтому все пути
# вычисляем сами, от места, где лежит сам скрипт: scripts/ -> tracker-deploy/
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_DIR="$(dirname "$SCRIPT_DIR")"

BACKUP_DIR="/var/backups/tracker"
LOG_FILE="/var/log/tracker-backup.log"

# Сколько дней храним копии — одинаково локально и в бакете. База весит единицы
# мегабайт, места не жалко; 30 дней это запас на «заметить, что данные испортились
# неделю назад».
RETENTION_DAYS=30

# --- Выгрузка в облако ------------------------------------------------------
S3_REMOTE="timeweb:tracker-backups-f"                        # remote из rclone.conf + бакет
PASSPHRASE_FILE="/root/.config/tracker-backup.passphrase"    # пароль gpg, копия — в менеджере паролей
# cron не наследует пользовательское окружение, поэтому конфиг rclone задаём явно,
# а не полагаемся на то, что $HOME окажется /root.
export RCLONE_CONFIG="/root/.config/rclone/rclone.conf"

# Обёртка над docker compose: тот же набор флагов, что и в остальных командах
# прода, чтобы не разъезжалось (см. README).
COMPOSE=(docker compose
  --env-file "$DEPLOY_DIR/.env.prod"
  -f "$DEPLOY_DIR/docker-compose.prod.yml")

# --- Логирование ------------------------------------------------------------
# Весь вывод скрипта (и stdout, и stderr) уходит и в лог-файл, и на экран:
# в cron экрана нет, а при ручном запуске хочется видеть, что происходит.
mkdir -p "$BACKUP_DIR"
chmod 700 "$BACKUP_DIR"   # в дампе персональные данные — чужим читать нечего
exec > >(tee -a "$LOG_FILE") 2>&1

log() { echo "[$(date '+%F %T')] $*"; }

# Шифрует файл и кладёт в бакет, во вложенную «папку» $2.
# --symmetric — шифрование одним паролем, без ключевых пар: расшифровать сможет
#   любой, у кого есть пароль, ключи никуда возить не надо.
# --batch/--yes — не задавать вопросов: в cron отвечать на них некому.
# Зашифрованную копию после отправки удаляем: локально держим открытый дамп,
# его восстанавливать быстрее, а диск сервера и так доступен только root.
upload() {
  local file="$1" subdir="$2"
  log "Шифрую и отправляю в $S3_REMOTE/$subdir/"
  gpg --batch --yes --symmetric --cipher-algo AES256 \
    --passphrase-file "$PASSPHRASE_FILE" \
    --output "$file.gpg" "$file"
  rclone copy "$file.gpg" "$S3_REMOTE/$subdir/"
  rm -f "$file.gpg"
}

log "=== Старт бэкапа ==="

# --- Проверка, что база вообще поднята --------------------------------------
# exec работает только с запущенным контейнером. Если db лежит — честно падаем
# с внятным сообщением, а не создаём файл на 0 байт.
if ! "${COMPOSE[@]}" ps --status running --services | grep -qx db; then
  log "ОШИБКА: контейнер db не запущен, бэкап невозможен"
  exit 1
fi

# --- Дамп -------------------------------------------------------------------
DUMP_FILE="$BACKUP_DIR/tracker-db-$(date +%F_%H%M%S).dump"

# -T   — не выделять псевдотерминал: в cron его нет, иначе команда упадёт.
# sh -c '...' в одинарных кавычках — переменные подставляет shell ВНУТРИ
#        контейнера, где POSTGRES_USER/POSTGRES_DB заданы в environment.
# -Fc  — custom-формат: уже сжат и разворачивается pg_restore выборочно.
# Postgres снимает дамп внутри транзакции, поэтому копия консистентна даже
# если прямо сейчас кто-то диктует трату голосом. Останавливать базу не нужно.
log "Снимаю дамп в $DUMP_FILE"
"${COMPOSE[@]}" exec -T db \
  sh -c 'pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc' > "$DUMP_FILE"

chmod 600 "$DUMP_FILE"

# --- Санити-чек -------------------------------------------------------------
# Дешёвая проверка «файл не пустой»: ловит самый частый тихий сбой, когда
# pg_dump отвалился, а файл создался. Настоящая проверка — прогон restore.sh
# на локальной базе, её делаем руками (см. README).
DUMP_SIZE=$(stat -c %s "$DUMP_FILE")
if [ "$DUMP_SIZE" -lt 1000 ]; then
  log "ОШИБКА: дамп подозрительно мал ($DUMP_SIZE байт), удаляю"
  rm -f "$DUMP_FILE"
  exit 1
fi
log "Готово: $(du -h "$DUMP_FILE" | cut -f1)"

upload "$DUMP_FILE" db

# --- Секреты и сертификаты, раз в неделю -------------------------------------
# .env.prod существует только на этом сервере: потеряешь — потеряешь пароль к
# базе и ключи Nexara/OpenRouter. certbot/conf — TLS-сертификат: перевыпускается,
# но у Let's Encrypt есть лимиты на частоту, копия экономит нервы.
# date +%u возвращает день недели (1=понедельник … 7=воскресенье).
# FORCE_SECRETS=1 — прогнать эту ветку в любой день: нужно, чтобы проверить её
# руками, не дожидаясь воскресенья и не правя условие временно через sed.
if [ "$(date +%u)" = "7" ] || [ "${FORCE_SECRETS:-0}" = "1" ]; then
  SECRETS_FILE="$BACKUP_DIR/tracker-secrets-$(date +%F).tar.gz"
  log "Воскресенье: архивирую секреты в $SECRETS_FILE"
  tar -czf "$SECRETS_FILE" -C "$DEPLOY_DIR" .env.prod certbot/conf
  chmod 600 "$SECRETS_FILE"
  upload "$SECRETS_FILE" secrets
fi

# --- Ретеншн ----------------------------------------------------------------
# -mtime +N — файлы, изменённые более N суток назад. Без этой строки диск
# однажды заполнится и уронит прод — классический способ убить сервер бэкапами.
log "Удаляю локальные копии старше $RETENTION_DAYS дней"
find "$BACKUP_DIR" -type f -name 'tracker-*' -mtime +"$RETENTION_DAYS" -print -delete

# В бакете ретеншн отдельный: rclone удаляет объекты старше того же срока.
# --min-age у rclone означает «объекты не моложе», то есть ровно старые.
log "Удаляю копии в бакете старше $RETENTION_DAYS дней"
rclone delete --min-age "${RETENTION_DAYS}d" "$S3_REMOTE/db/"
rclone delete --min-age "${RETENTION_DAYS}d" "$S3_REMOTE/secrets/"

log "=== Бэкап завершён ==="
